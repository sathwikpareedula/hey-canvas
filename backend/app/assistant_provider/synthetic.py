"""Synthetic provider used for precise unit testing without live providers."""

from app.assistant_orchestration.models import (
    AcademicModelProvider,
    AssistantEvent,
    AssistantEventType,
    AssistantModelInput,
)
from app.assistant_tools.models import (
    AssistantEvidenceReference,
    AssistantResponse,
    AssistantResponseBlock,
    ResponseBlockType,
)


class SyntheticAcademicModelProvider(AcademicModelProvider):
    """Deterministic local-only provider for tests and offline development."""

    def __init__(
        self,
        *,
        failure: bool = False,
        malformed: bool = False,
        oversized: bool = False,
        streaming: bool = False,
    ) -> None:
        self.failure = failure
        self.malformed = malformed
        self.oversized = oversized
        self.streaming = streaming

    def complete(self, model_input: AssistantModelInput) -> AssistantResponse:
        if self.failure:
            raise RuntimeError("provider unavailable")
        if self.malformed:
            raise ValueError("provider malformed output")
        text = self._make_text(model_input)
        if self.oversized:
            text = "x" * 5000
        refs: list[AssistantEvidenceReference] = []
        seen: set[str] = set()
        for e in model_input.evidence:
            if e.canvas_file_id and e.canvas_file_id not in seen:
                seen.add(e.canvas_file_id)
                refs.append(
                    AssistantEvidenceReference(
                        authority=e.authority,
                        identifier=e.canvas_file_id,
                    )
                )
        return AssistantResponse(
            status="ok",
            blocks=(
                AssistantResponseBlock(
                    type=ResponseBlockType.TEXT,
                    text=text[:4000],
                    references=tuple(refs),
                ),
            ),
            course_id=model_input.plan.course_id,
        )

    def stream(self, model_input: AssistantModelInput) -> tuple[AssistantEvent, ...]:
        if self.failure:
            raise RuntimeError("provider unavailable")
        text = self._make_text(model_input)
        if self.oversized:
            text = "x" * 5000
        refs: list[AssistantEvidenceReference] = []
        seen: set[str] = set()
        for e in model_input.evidence:
            if e.canvas_file_id and e.canvas_file_id not in seen:
                seen.add(e.canvas_file_id)
                refs.append(
                    AssistantEvidenceReference(
                        authority=e.authority,
                        identifier=e.canvas_file_id,
                    )
                )
        response = AssistantResponse(
            status="ok",
            blocks=(
                AssistantResponseBlock(
                    type=ResponseBlockType.TEXT,
                    text=text[:4000],
                    references=tuple(refs),
                ),
            ),
            course_id=model_input.plan.course_id,
        )
        if self.streaming:
            return (
                AssistantEvent(type=AssistantEventType.STARTED),
                AssistantEvent(
                    type=AssistantEventType.TEXT_DELTA,
                    text=text[:200],
                ),
                AssistantEvent(
                    type=AssistantEventType.COMPLETED,
                    response=response,
                ),
            )
        return (
            AssistantEvent(type=AssistantEventType.STARTED),
            AssistantEvent(
                type=AssistantEventType.COMPLETED,
                response=response,
            ),
        )

    @staticmethod
    def _make_text(model_input: AssistantModelInput) -> str:
        q = model_input.request.query.casefold()
        if "admissible" in q and "a*" in q:
            return (
                "In A* search, an admissible heuristic is a heuristic function h(n) "
                "that never overestimates the true cost to reach the goal from node n. "
                "For all nodes n, 0 <= h(n) <= h*(n), guaranteeing that A* returns an "
                "optimal solution."
            )
        if "consistent" in q or "consistency" in q:
            return (
                "In A* search, a heuristic function h(n) is consistent (or monotonic) if for "
                "every node n and successor n' generated by action a: h(n) <= c(n, a, n') + h(n'), "
                "with h(goal) = 0. A consistent heuristic satisfies the triangle inequality "
                "and is always admissible."
            )
        if "time complexity" in q and ("a*" in q or model_input.plan.course_id == "ai"):
            return (
                "The time complexity of A* search depends heavily on the heuristic function. "
                "In the worst case with an uninformative heuristic, it can be exponential O(b^d), "
                "where b is the branching factor and d is the goal depth."
            )
        if (
            any(t in q for t in ("summarize this professor pdf", "summarize", "professor pdf"))
            and model_input.evidence
        ):
            return (
                "Based on the provided professor document, forward kinematics describes "
                "the relationship between the manipulator joint angles and the resulting "
                "position and orientation of the end-effector in the workspace."
            )
        return (
            f"I can help with: {model_input.request.query}. "
            f"Course context: {model_input.plan.course_id or 'unresolved'}."
        )
